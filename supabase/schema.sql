-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.email_subscribers (
  id bigint generated by default as identity primary key,
  email text not null unique,
  interests text[] not null default '{}',
  consent_at timestamptz not null default now(),
  source text not null default 'rathore-creators-hub',
  created_at timestamptz not null default now()
);

-- Keep the table private. Only the server API uses the service-role key.
alter table public.email_subscribers enable row level security;
-- Do not create public SELECT/INSERT policies. Never expose the service-role key in NEXT_PUBLIC variables.
